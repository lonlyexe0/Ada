import AppKit
import SwiftUI

/// Son kopyalanan yazılar.
/// - Varsayılan olarak KAPALI: paneldeki "Pano" sekmesinden ya da menüden açılır.
/// - Sadece bellekte tutulur (diske yazılmaz, Ada kapanınca silinir).
/// - Şifre yöneticilerinin "gizli" diye işaretlediği kopyalamalar kaydedilmez.
/// - macOS pano okumayı her seferinde soruyorsa Ada okumayı bırakır (her kopyalamada uyarı çıkmasın);
///   Sistem Ayarları'nda Ada'ya "her zaman izin ver" denince kaldığı yerden devam eder.
@MainActor
final class ClipboardHistory: ObservableObject {
    @Published private(set) var items: [String] = []
    /// Az önce tekrar kopyalanan (kısa süre ✓ gösterilir).
    @Published private(set) var justCopied: String?
    /// macOS pano okumaya izin vermiyor ya da her seferinde soruyor.
    @Published private(set) var blocked = false
    /// Menüden ya da panodan açılıp kapatılır ("Pano geçmişi").
    @Published var enabled: Bool {
        didSet {
            guard !isPreview, enabled != oldValue else { return }
            UserDefaults.standard.set(enabled, forKey: Self.enabledKey)
            if enabled {
                lastChange = -1 // açılınca o anki panoyu da al
                poll()
            } else {
                items.removeAll()
                blocked = false
            }
        }
    }

    static let limit = 10
    private static let enabledKey = "clipboardHistory"
    /// Bu türler varsa kayıt yok: şifre yöneticileri ve geçici kopyalamalar (nspasteboard.org kuralı).
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    private let isPreview: Bool
    private var lastChange = NSPasteboard.general.changeCount

    init(preview: Bool = false) {
        isPreview = preview
        enabled = preview || (UserDefaults.standard.object(forKey: Self.enabledKey) as? Bool ?? false)
        guard !preview else { return }
        Task { [weak self] in
            while true {
                try? await Task.sleep(nanoseconds: 800_000_000)
                guard let self else { return }
                self.poll()
            }
        }
    }

    /// Pano değişti mi? (Sayaç her zaman okunabilir; içeriğe sadece değişince ve izin varsa bakılır.)
    private func poll() {
        let pasteboard = NSPasteboard.general
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard enabled else { return }
        guard Self.mayRead(pasteboard) else {
            blocked = true
            return
        }
        let types = pasteboard.types?.map(\.rawValue) ?? []
        let text = types.contains(where: Self.skippedTypes.contains) ? nil : pasteboard.string(forType: .string)
        // macOS az önce sorduysa ve "her zaman izin ver" denmediyse bundan sonra okumayalım
        blocked = !Self.mayRead(pasteboard)
        guard let clean = text?.trimmingCharacters(in: .whitespacesAndNewlines), !clean.isEmpty else { return }
        remember(String(clean.prefix(2000)))
    }

    /// macOS 15.4+: "Sor" ya da "Engelle" ise okumayız. "Varsayılan" (hiç sorulmamış) ise
    /// ilk okumada macOS bir kez sorar; sonra durum "Sor"a döner ve okumayı bırakırız.
    private static func mayRead(_ pasteboard: NSPasteboard) -> Bool {
        guard #available(macOS 15.4, *) else { return true }
        switch pasteboard.accessBehavior {
        case .alwaysAllow, .default: return true
        case .ask, .alwaysDeny: return false
        @unknown default: return false
        }
    }

    private func remember(_ text: String) {
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Tıklanan yazıyı tekrar panoya koy.
    func copy(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount // kendi kopyalamamızı tekrar kaydetmeyelim
        remember(text)
        justCopied = text
        Task { [weak self] in
            try? await Task.sleep(nanoseconds: 1_500_000_000)
            if self?.justCopied == text { self?.justCopied = nil }
        }
    }

    func clear() {
        items.removeAll()
    }

    /// Gizlilik ve Güvenlik ayarlarını aç (pano izni orada).
    func openPrivacySettings() {
        guard let url = URL(string: "x-apple.systempreferences:com.apple.preference.security") else { return }
        NSWorkspace.shared.open(url)
    }

    func loadPreview() {
        items = ["git push -u origin main", "https://lrclib.net", "Fizik ödevi: 3. bölüm, 12-18 arası"]
    }
}

/// "Pano" sekmesi.
struct ClipboardView: View {
    @ObservedObject var clipboard: ClipboardHistory

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack {
                Text(verbatim: "Son kopyaladıkların")
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundStyle(.white.opacity(0.5))
                Spacer()
                if clipboard.enabled, !clipboard.items.isEmpty {
                    Button { clipboard.clear() } label: {
                        Text(verbatim: "Temizle")
                            .font(.system(size: 11, weight: .semibold))
                            .foregroundStyle(.white.opacity(0.6))
                    }
                    .buttonStyle(PressScaleStyle())
                }
            }
            if !clipboard.enabled {
                notice("Pano geçmişi kapalı. Açarsan kopyaladığın son 10 yazı burada durur (sadece bellekte, diske yazılmaz).",
                       button: "Aç", symbol: "power") { clipboard.enabled = true }
            } else if clipboard.blocked, clipboard.items.isEmpty {
                notice("macOS pano okumayı her seferinde soruyor. Sistem Ayarları → Gizlilik ve Güvenlik'te Ada'ya pano için \"her zaman izin ver\" de.",
                       button: "Ayarları aç", symbol: "gearshape.fill") { clipboard.openPrivacySettings() }
            } else if clipboard.items.isEmpty {
                notice("Kopyaladığın yazılar burada görünecek. Tıklayınca tekrar kopyalanır.")
            } else {
                if clipboard.blocked {
                    Text(verbatim: "macOS izin vermediği için yeni kopyalananlar eklenmiyor")
                        .font(.system(size: 10.5, weight: .medium))
                        .foregroundStyle(.orange.opacity(0.8))
                }
                list
            }
        }
        .padding(.horizontal, 22)
        .padding(.vertical, 8)
    }

    @ViewBuilder
    private var list: some View {
        let rows = VStack(spacing: 4) {
            ForEach(Array(clipboard.items.enumerated()), id: \.offset) { item in
                row(item.element)
            }
        }
        // (Resim çıkarırken kaydırma alanı çizilemiyor, düz liste kullan)
        if Snapshot.isRendering {
            rows.frame(maxHeight: .infinity, alignment: .top).clipped()
        } else {
            ScrollView(.vertical, showsIndicators: false) { rows }
        }
    }

    private func row(_ text: String) -> some View {
        Button { clipboard.copy(text) } label: {
            HStack(spacing: 8) {
                Text(verbatim: text.split(whereSeparator: \.isNewline).joined(separator: " "))
                    .font(.system(size: 12))
                    .foregroundStyle(.white.opacity(0.85))
                    .lineLimit(1)
                    .truncationMode(.tail)
                Spacer(minLength: 4)
                Image(systemName: clipboard.justCopied == text ? "checkmark" : "doc.on.doc")
                    .font(.system(size: 10, weight: .semibold))
                    .foregroundStyle(clipboard.justCopied == text ? Color.green : .white.opacity(0.4))
            }
            .padding(.horizontal, 10)
            .frame(height: 24)
            .background(RoundedRectangle(cornerRadius: 7, style: .continuous).fill(Color.white.opacity(0.07)))
            .contentShape(Rectangle())
        }
        .buttonStyle(PressScaleStyle())
    }

    private func notice(_ text: String, button: String? = nil, symbol: String = "",
                        action: @escaping () -> Void = {}) -> some View {
        VStack(spacing: 10) {
            Text(verbatim: text)
                .font(.system(size: 12))
                .foregroundStyle(.white.opacity(0.5))
                .multilineTextAlignment(.center)
            if let button {
                PillButton(title: button, symbol: symbol, action: action)
            }
        }
        .padding(.horizontal, 20)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }
}
